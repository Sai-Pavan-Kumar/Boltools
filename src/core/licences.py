"""Licences window data: the components Boltools ships and their full licence texts.

software/licenses/ is generated by tools_dev/collect_licences.py and bundled with the
app. The UI may only ask for a file that index.json lists for that component, so a
request can never read anything else on disk.
"""

import json
import os
from typing import Any, Dict, List, Optional

from src._build import APP_VERSION
from src.core.paths import get_base_dir

MAX_TEXT_BYTES = 512 * 1024


def _licences_dir() -> str:
    return os.path.join(get_base_dir(), "licenses")


def _index(licences_dir: Optional[str] = None) -> List[Dict[str, Any]]:
    try:
        with open(os.path.join(licences_dir or _licences_dir(), "index.json"), encoding="utf-8") as f:
            components = json.load(f).get("components", [])
    except (OSError, ValueError, AttributeError):
        return []
    return [c for c in components if isinstance(c, dict) and c.get("id") and isinstance(c.get("files"), list)]


def list_components(licences_dir: Optional[str] = None) -> Dict[str, Any]:
    return {"app_version": APP_VERSION, "components": _index(licences_dir)}


def read_text(comp_id: str, file_name: str, licences_dir: Optional[str] = None) -> Optional[str]:
    """Full text of one listed licence file, or None for anything not in the index."""
    folder = licences_dir or _licences_dir()
    entry = next((c for c in _index(folder) if c["id"] == comp_id), None)
    if not entry or file_name not in entry["files"]:
        return None
    path = os.path.join(folder, entry["id"], file_name)
    try:
        if os.path.getsize(path) > MAX_TEXT_BYTES:
            return None
        with open(path, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return None


class LicencesApi:
    """Bridge calls for the Licences window, mixed into DesktopBridge."""

    def get_licences(self) -> Dict[str, Any]:
        return list_components()

    def read_licence(self, comp_id: str, file_name: str) -> Optional[str]:
        return read_text(str(comp_id), str(file_name))
